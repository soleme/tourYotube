const WorldMap = {
  canvas: null,
  build() {
    const mask = makeCanvas(W, H), mg = mask.g;
    const fillPoly = (poly, col) => {
      mg.fillStyle = col; mg.beginPath();
      for (let i = 0; i < poly.length; i += 2) { const [x, y] = proj(poly[i], poly[i + 1]); if (i === 0) mg.moveTo(x, y); else mg.lineTo(x, y); }
      mg.closePath(); mg.fill();
    };
    for (const p of LAND) fillPoly(p, '#ffffff');
    for (const p of WATER) fillPoly(p, '#000000');
    const md = mg.getImageData(0, 0, W, H).data;
    const land = new Uint8Array(W * H);
    for (let i = 0; i < W * H; i++) land[i] = md[i * 4] > 128 && md[i * 4 + 3] > 128 ? 1 : 0;
    for (let x = 0; x < W; x++) for (let y = 0; y < MAP_Y0; y++) land[y * W + x] = 0;
    const isL = (x, y) => x >= 0 && y >= 0 && x < W && y < H && land[y * W + x];
    const c = makeCanvas(W, H), g = c.g;
    const id = g.createImageData(W, H), d = id.data;
    const noise = (x, y) => { const s = Math.sin(x * 12.9898 + y * 78.233) * 43758.5453; return s - Math.floor(s); };
    const put = (x, y, hex) => { const [r, gg, b] = hex2rgb(hex); const i = (y * W + x) * 4; d[i] = r; d[i + 1] = gg; d[i + 2] = b; d[i + 3] = 255; };
    for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) {
      const [lon, lat] = unproj(x + 0.5, y + 0.5);
      if (isL(x, y)) {
        let col;
        const n = noise(x, y);
        if (lat > 68 || lat < -60) col = n < 0.3 ? '#dfe8f2' : '#f4f8fc';
        else if (lat > 58) col = n < 0.5 ? '#5e8f6a' : '#6f9f78';
        else if ((lon > -17 && lon < 35 && lat > 15 && lat < 32) || (lon > 35 && lon < 60 && lat > 14 && lat < 33) || (lon > 118 && lon < 145 && lat > -31 && lat < -19) || (lon > 85 && lon < 115 && lat > 38 && lat < 47) || (lon > -117 && lon < -103 && lat > 28 && lat < 37) || (lon > 55 && lon < 70 && lat > 25 && lat < 42))
          col = n < 0.25 ? '#e0b765' : '#ecc977';
        else if (Math.abs(lat) < 11 + noise(x * 3, 7) * 4) col = n < 0.4 ? '#2f8a4a' : '#3a9a52';
        else col = n < 0.3 ? '#5aac54' : n < 0.85 ? '#6cbf5c' : '#82cc66';
        // 해안선 진하게
        if (!isL(x + 1, y) || !isL(x - 1, y) || !isL(x, y + 1) || !isL(x, y - 1)) col = shade(col, -0.18);
        put(x, y, col);
      } else {
        let near = 0;
        for (let dy = -2; dy <= 2 && !near; dy++) for (let dx = -2; dx <= 2; dx++) if (isL(x + dx, y + dy)) { near = Math.abs(dx) + Math.abs(dy) <= 2 ? 1 : 0; if (near) break; }
        let col = near ? '#4ea4dc' : ((x + y) % 2 === 0 ? '#2e74c4' : '#3079c9');
        if (!near && (y - MAP_Y0) % 22 === 0 && x % 2 === 0) col = '#3d86d4';
        if (!near && x % 40 === 0 && y % 2 === 0 && y > MAP_Y0) col = '#3d86d4';
        put(x, y, col);
      }
    }
    g.putImageData(id, 0, 0);
    this.canvas = c;
  },
};
